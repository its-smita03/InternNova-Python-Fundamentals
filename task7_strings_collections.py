# String
text = "Python Programming"
print("Upper:", text.upper())
print("Lower:", text.lower())
print("Replace:", text.replace("Python", "Data"))
print("Find:", text.find("Programming"))

# List
fruits = ["Apple", "Banana", "Mango"]
fruits.append("Orange")
fruits.remove("Banana")
fruits.sort()
print("List:", fruits)

# Tuple
numbers = (10, 20, 30)
print("Tuple:", numbers)
print("Index 1:", numbers[1])

# Dictionary
student = {"Name": "Smita", "Branch": "BCA", "Marks": 85}
print("Dictionary:", student)

# Set
s = {1, 2, 3}
s.add(4)
s.remove(2)
print("Set:", s)
